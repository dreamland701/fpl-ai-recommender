"""Plan-horizon RL environment, rebuilt after the 2026-10 review (G5).

Replaces grpo_plan_env.py's defects (review P0-04, P1-07..P1-10):

- The observation at origin week t uses only what is known at t: the squad,
  bank, free transfers, chips, the t forecasts, and a K-week outlook split
  from t's own 1/3/5-week heads. Later weeks' states are used only to execute
  and score the plan, never to describe it.
- Each week's action picks among complete legal moves generated by the exact
  optimizer (hold, best single transfer, best two transfers, wildcard, free
  hit) for the squad the plan has actually reached, plus a captain and a chip.
- Scoring follows the official rules (fpl_ai.rules): automatic substitutions,
  vice-captain cover, triple captain, bench boost, half-profit selling prices,
  season-correct free-transfer caps.
- Rewards are paired against a deterministic planner holding the same chips
  and free transfers, so spending a chip earns nothing by itself.
- Plans must be exactly K schema-valid weekly actions; nothing is padded.

TRL- and model-free; unit-tested on CPU (tests/test_grpo_plan_env_v2.py).
"""

from __future__ import annotations

import json
import math
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Sequence, Tuple

from .grpo_env import WeeklyState
from .rules import automatic_substitutions, selling_price
from .types import SquadPlayer

TRANSFER_OPTIONS = ("hold", "best1", "best2")
CHIPS = ("bench_boost", "triple_captain", "wildcard", "free_hit")
HIT = 4
FIRST_HALF_LAST_WEEK = 19
UNPARSEABLE_REWARD = -5.0
# Outlook split of the origin heads: week 1 = 1GW, weeks 2-3 share (3GW-1GW),
# weeks 4-5 share (5GW-3GW). Beyond five weeks no origin forecast exists.
MAX_HORIZON = 5
# FPL_PLANNER_DISCIPLINE=1 (G7b on): the planner's transfer each week is "auto" = the best single move only
# if it beats holding by FPL_PLANNER_MIN_GAIN projected points (5-week values), else bank the free transfer.
# The real decision engine already holds this way (59 transfers in 84 backtest weeks; demanding more than
# ~1 point of gain loses squad points there), while "best1 every week" was a strawman the LLM beat by holding.
PLANNER_DISCIPLINE = __import__("os").environ.get("FPL_PLANNER_DISCIPLINE", "0") == "1"
PLANNER_MIN_GAIN = float(__import__("os").environ.get("FPL_PLANNER_MIN_GAIN", "1.0"))


def chip_half(week: int) -> int:
    return 1 if week <= FIRST_HALF_LAST_WEEK else 2


def max_free_transfers(season: str) -> int:
    """Banking cap: 2 until 2023-24, 5 from 2024-25."""
    return 5 if season >= "2024-25" else 2


def outlook_points(forecast, week_index: int) -> float:
    one, three, five = forecast.predicted_points_1gw, forecast.predicted_points_3gw, forecast.predicted_points_5gw
    if week_index == 0:
        return one
    if week_index in (1, 2):
        return max(0.0, (three - one) / 2.0)
    return max(0.0, (five - three) / 2.0)


@dataclass(frozen=True)
class WeekAction:
    transfer: str = "hold"
    captain: Optional[int] = None
    chip: str = "none"


def parse_plan(text: str, horizon: int) -> Optional[List[WeekAction]]:
    """Exactly `horizon` schema-valid actions, or None. No padding, no defaults."""
    try:
        parsed = json.loads(text.strip())
    except json.JSONDecodeError:
        start, end = text.find("["), text.rfind("]")
        if start == -1 or end <= start:
            return None
        try:
            parsed = json.loads(text[start:end + 1])
        except json.JSONDecodeError:
            return None
    if not isinstance(parsed, list) or len(parsed) != horizon:
        return None
    actions = []
    for entry in parsed:
        if not isinstance(entry, dict):
            return None
        transfer, chip, captain = entry.get("transfer"), entry.get("chip", "none"), entry.get("captain")
        if transfer not in TRANSFER_OPTIONS or (chip != "none" and chip not in CHIPS):
            return None
        if captain is not None and (isinstance(captain, bool) or not isinstance(captain, int)):
            return None
        actions.append(WeekAction(transfer=transfer, captain=captain, chip=chip))
    return actions


@dataclass
class Squad:
    players: Dict[int, dict]  # player_id -> {"position", "team_id", "purchase", "sell"}
    bank: float
    free_transfers: int

    def copy(self) -> "Squad":
        return Squad({k: dict(v) for k, v in self.players.items()}, self.bank, self.free_transfers)

    def signature(self) -> Tuple:
        return (tuple(sorted(self.players)), round(self.bank, 1), self.free_transfers)


@dataclass
class RolloutResult:
    plan: Optional[List[WeekAction]]
    realized: float
    reward: float
    advantage: float = 0.0
    detail: List[Dict[str, object]] = field(default_factory=list)


class PlanEnvV2:
    """Executes K-week plans from one origin state; `optimizer` supplies moves.

    optimizer(forecasts, value, current_sell, bank, free_transfers, wildcard,
    max_transfers) -> dict(squad, out, in, hits, net, bank_after) is
    reports/gw6_packet_2026_10/squad_milp.optimize (or a test double).
    """

    def __init__(self, states: Sequence[WeeklyState], optimizer, chips: Optional[Dict[int, frozenset]] = None,
                 wildcard_bench: bool = False):
        """wildcard_bench (10-12, chip sequencing): a wildcard rebuild also values the bench for a bench
        boost the week after (the standard rebuild credits a bench player a tenth of a starter and buys
        the cheapest bench; a bench boost after it was worth 10.6 vs 14.4 in the chip-timing tables)."""
        assert 1 <= len(states) <= MAX_HORIZON
        assert len({s.season for s in states}) == 1
        self.states = list(states)
        self.horizon = len(states)
        self.optimizer = optimizer
        chips = chips or {}
        self.chips = {1: frozenset(chips.get(1, CHIPS)), 2: frozenset(chips.get(2, CHIPS))}
        self._baseline: Optional[float] = None
        self._move_cache: Dict[Tuple, dict] = {}
        self.wildcard_bench = wildcard_bench

    # ---------------------------------------------------------------- helpers
    def _start_squad(self) -> Squad:
        s0 = self.states[0]
        players = {p.player_id: {"position": p.position, "team_id": p.team_id,
                                 "purchase": p.purchase_price, "sell": p.sell_price} for p in s0.squad}
        return Squad(players, float(s0.bank), int(s0.free_transfers))

    @staticmethod
    def _forecast_table(state: WeeklyState) -> Dict[int, dict]:
        return {f.player_id: {"name": f.player_name, "pos": f.position, "team_id": f.team_id, "price": f.price,
                              "status": "a", "p1": f.predicted_points_1gw, "p3": f.predicted_points_3gw, "p5": f.predicted_points_5gw,
                              "papp": f.appearance_probability} for f in state.forecasts}

    def _refresh_sell(self, squad: Squad, table: Dict[int, dict]) -> None:
        for pid, p in squad.players.items():
            if pid in table and table[pid]["price"] > 0:
                p["sell"] = selling_price(p["purchase"], table[pid]["price"])

    def _move(self, week_index: int, squad: Squad, option: str) -> dict:
        key = (week_index, squad.signature(), option, self.wildcard_bench if option == "wildcard" else None)
        if key in self._move_cache:
            return self._move_cache[key]
        state = self.states[week_index]
        table = self._forecast_table(state)
        sell = {pid: p["sell"] for pid, p in squad.players.items()}
        if option == "free_hit":
            value = {pid: r["p1"] for pid, r in table.items()}
            result = self.optimizer(table, value, sell, squad.bank, wildcard=True)
        elif option == "wildcard":
            value = {pid: r["p5"] for pid, r in table.items()}
            if self.wildcard_bench:
                # bench credit = the usual tenth for sitting out plus the player's forecast for next week
                # (second week of the 3-week forecast, from this origin only), when the bench boost plays him
                bench = {pid: 0.1 * r["p5"] * (r["pos"] != "GK") + max(0.0, (r["p3"] - r["p1"]) / 2) for pid, r in table.items()}
                result = self.optimizer(table, value, sell, squad.bank, wildcard=True, bench_value=bench)
            else:
                result = self.optimizer(table, value, sell, squad.bank, wildcard=True)
        elif option == "hold0":
            value = {pid: r["p5"] for pid, r in table.items()}
            result = self.optimizer(table, value, sell, squad.bank, free_transfers=squad.free_transfers, max_transfers=0)
        else:
            k = {"best1": 1, "best2": 2}[option]
            value = {pid: r["p5"] for pid, r in table.items()}
            result = self.optimizer(table, value, sell, squad.bank, free_transfers=squad.free_transfers,
                                    max_transfers=k)
        self._move_cache[key] = result
        return result

    def _apply(self, squad: Squad, move: dict, table: Dict[int, dict], wildcard: bool) -> Tuple[Squad, int]:
        new = squad.copy()
        for pid in move["out"]:
            new.players.pop(pid)
        for pid in move["in"]:
            r = table[pid]
            new.players[pid] = {"position": r["pos"], "team_id": r["team_id"], "purchase": r["price"], "sell": r["price"]}
        new.bank = round(move["bank_after"], 1)
        hits = 0 if wildcard else int(move["hits"])
        return new, hits

    @staticmethod
    def _lineup(squad: Squad, table: Dict[int, dict]):
        value = {pid: table.get(pid, {}).get("p1", 0.0) for pid in squad.players}
        by = {pos: sorted((pid for pid, p in squad.players.items() if p["position"] == pos), key=lambda i: -value[i])
              for pos in ("GK", "DEF", "MID", "FWD")}
        best = None
        for d in range(3, 6):
            for f in range(1, 4):
                m = 10 - d - f
                if not 2 <= m <= 5 or len(by["DEF"]) < d or len(by["MID"]) < m or len(by["FWD"]) < f:
                    continue
                xi = by["GK"][:1] + by["DEF"][:d] + by["MID"][:m] + by["FWD"][:f]
                score = sum(value[i] for i in xi)
                if best is None or score > best[0]:
                    best = (score, xi)
        xi = best[1]
        ranked = sorted(xi, key=lambda i: -value[i])
        bench = by["GK"][1:2] + sorted((i for i in squad.players if i not in xi and squad.players[i]["position"] != "GK"),
                                       key=lambda i: -value[i])
        return xi, bench, ranked[0], ranked[1]

    # ---------------------------------------------------------------- rollout
    def rollout(self, plan: Sequence[WeekAction], return_state: bool = False):
        """Score a plan; with return_state, also hand back where it left the manager
        (squad as SquadPlayer list with purchase/selling prices, bank, free
        transfers, chips left per half) for closed-loop season evaluation."""
        assert len(plan) == self.horizon
        squad = self._start_squad()
        cap = max_free_transfers(self.states[0].season)
        remaining = {1: set(self.chips[1]), 2: set(self.chips[2])}
        total, details = 0.0, []
        for index, (state, action) in enumerate(zip(self.states, plan)):
            table = self._forecast_table(state)
            self._refresh_sell(squad, table)
            half = chip_half(state.week)
            chip = action.chip if action.chip in remaining[half] else "none"
            if chip != "none":
                remaining[half].discard(chip)
            hits, transfers_made, saved = 0, 0, None
            if chip in ("wildcard", "free_hit"):
                try:
                    move = self._move(index, squad, chip)
                except RuntimeError:
                    # no legal 15 exists this week (2025-26 week 22: the free-hit rebuild is infeasible); the
                    # chip cannot be played, so it is kept and the week is played as "none"
                    remaining[half].add(chip)
                    chip = "none"
            if chip in ("wildcard", "free_hit"):
                if chip == "free_hit":
                    saved = squad.copy()
                squad, hits = self._apply(squad, move, table, wildcard=True)
            elif action.transfer == "auto":
                move = self._move(index, squad, "best1")
                if move["in"] and move["net"] - self._move(index, squad, "hold0")["net"] >= PLANNER_MIN_GAIN:
                    squad, hits = self._apply(squad, move, table, wildcard=False)
                    transfers_made = len(move["in"])
            elif action.transfer != "hold":
                move = self._move(index, squad, action.transfer)
                squad, hits = self._apply(squad, move, table, wildcard=False)
                transfers_made = len(move["in"])
            xi, bench, captain, vice = self._lineup(squad, table)
            if action.captain is not None and action.captain in xi:
                vice = captain if action.captain != captain else vice
                captain = action.captain
            positions = {pid: p["position"] for pid, p in squad.players.items()}
            points, minutes = state.actual_points, state.actual_minutes
            if chip == "bench_boost":
                counted = [pid for pid in list(xi) + list(bench) if minutes.get(pid, 0.0) > 0]
            else:
                counted, _ = automatic_substitutions(positions, xi, bench, minutes)
            armband = captain if minutes.get(captain, 0.0) > 0 else (vice if minutes.get(vice, 0.0) > 0 else None)
            multiplier = 3 if chip == "triple_captain" else 2
            realized = sum(points.get(pid, 0.0) for pid in counted) - hits
            if armband is not None:
                realized += (multiplier - 1) * points.get(armband, 0.0)
            total += realized
            if chip in ("wildcard", "free_hit"):
                squad.free_transfers = min(cap, squad.free_transfers + 1)
            elif transfers_made:
                squad.free_transfers = min(cap, max(0, squad.free_transfers - transfers_made) + 1)
            else:
                squad.free_transfers = min(cap, squad.free_transfers + 1)
            if saved is not None:
                saved.free_transfers = squad.free_transfers
                squad = saved
            # counterfactual chip values for this week (hindsight ceilings, scripts/chip_timing_tables.py):
            # the armband holder's points (one extra multiple = triple captain), the points a bench boost
            # would have added, and the best points any counted player scored (hindsight captain)
            armband_points = points.get(armband, 0.0) if armband is not None else 0.0
            all_playing = [pid for pid in list(xi) + list(bench) if minutes.get(pid, 0.0) > 0]
            bench_extra = sum(points.get(pid, 0.0) for pid in all_playing) - sum(points.get(pid, 0.0) for pid in counted)
            details.append({"week": state.week, "transfer": action.transfer, "chip": chip, "captain": captain,
                            "hits": hits, "realized": realized, "captain_points": armband_points,
                            "bench_extra": 0.0 if chip == "bench_boost" else bench_extra,
                            "best_xi_points": max((points.get(pid, 0.0) for pid in counted), default=0.0)})
        if not return_state:
            return total, details
        names = {f.player_id: f.player_name for f in self.states[-1].forecasts}
        players = [SquadPlayer(pid, names.get(pid, str(pid)), p["team_id"], p["position"], p["sell"], p["purchase"])
                   for pid, p in squad.players.items()]
        return total, details, {"squad": players, "bank": squad.bank, "free_transfers": squad.free_transfers,
                                "chips": {h: frozenset(v) for h, v in remaining.items()}}

    # ---------------------------------------------------------------- baseline
    def baseline_plan(self) -> List[WeekAction]:
        """Deterministic planner with the same chips, using origin-week information only.

        Transfers: best single move each week. Triple captain in the window week
        with the highest origin-projected captain score (if that half still has
        it); bench boost in the week with the highest origin-projected bench
        total. Wildcard and free hit unused (projected rebuild gains did not
        realise in the 21-window replay; see memory fpl-chip-calibration).
        """
        start = self.states[0]
        table = {f.player_id: f for f in start.forecasts}
        squad_ids = [p.player_id for p in start.squad if p.player_id in table]
        captain_scores, bench_scores = [], []
        for k in range(self.horizon):
            values = sorted((outlook_points(table[pid], k) for pid in squad_ids), reverse=True)
            captain_scores.append(values[0] if values else 0.0)
            bench_scores.append(sum(values[11:15]) if len(values) >= 15 else 0.0)
        plan = [WeekAction(transfer="auto" if PLANNER_DISCIPLINE else "best1") for _ in range(self.horizon)]
        for chip, scores in (("triple_captain", captain_scores), ("bench_boost", bench_scores)):
            order = sorted(range(self.horizon), key=lambda k: -scores[k])
            for k in order:
                if chip in self.chips[chip_half(self.states[k].week)] and plan[k].chip == "none":
                    plan[k] = WeekAction(transfer=plan[k].transfer, captain=None, chip=chip)
                    break
        return plan

    def baseline_total(self) -> float:
        if self._baseline is None:
            self._baseline, _ = self.rollout(self.baseline_plan())
        return self._baseline

    # ---------------------------------------------------------------- prompt
    def state_prompt(self, top_n_candidates: int = 15) -> str:
        start = self.states[0]
        table = {f.player_id: f for f in start.forecasts}
        squad = self._start_squad()
        self._refresh_sell(squad, self._forecast_table(start))
        squad_ids = set(squad.players)
        candidates = sorted((f for f in start.forecasts if f.player_id not in squad_ids),
                            key=lambda f: -f.predicted_points_5gw)[:top_n_candidates]

        def row(f, sell=None):
            price = f"£{sell:.1f} sell" if sell is not None else f"£{f.price:.1f}"
            return (f"{f.player_id}|{f.player_name}|{f.position}|{price}|1gw {f.predicted_points_1gw:.1f}"
                    f"|5gw {f.predicted_points_5gw:.1f}|P(app) {f.appearance_probability:.2f}")

        squad_lines = "\n".join(row(table[pid], squad.players[pid]["sell"]) for pid in squad.players if pid in table)
        cand_lines = "\n".join(row(f) for f in candidates)
        outlook = []
        for k in range(self.horizon):
            values = sorted((outlook_points(table[pid], k) for pid in squad_ids if pid in table), reverse=True)
            best_c = max((pid for pid in squad_ids if pid in table), key=lambda pid: outlook_points(table[pid], k))
            outlook.append(f"week {k + 1} (GW{start.week + k}): best XI-ish {sum(values[:11]):.0f}, bench {sum(values[11:15]):.1f}, "
                           f"top captain {table[best_c].player_name} {outlook_points(table[best_c], k):.1f}")
        proposals = []
        for option in ("best1", "best2", "wildcard", "free_hit"):
            move = self._move(0, squad, option)
            name = lambda i: table[i].player_name if i in table else str(i)  # noqa: E731
            if option in ("best1", "best2"):
                proposals.append(f"  {option}: {', '.join(map(name, move['out'])) or 'none'} -> "
                                 f"{', '.join(map(name, move['in'])) or 'none'} (hits {move['hits']})")
            else:
                proposals.append(f"  {option}: rebuild changes {len(move['in'])} players")
        chips_txt = "; ".join(
            f"{'GW1-19' if h == 1 else 'GW20-38'}: {', '.join(sorted(self.chips[h])) or 'none'}"
            for h in sorted({chip_half(s.week) for s in self.states}))
        return (
            f"FPL plan state — {start.season} GW{start.week}, horizon {self.horizon} weeks\n"
            f"Bank £{squad.bank:.1f} | Free transfers {squad.free_transfers} (max {max_free_transfers(start.season)}) | "
            f"Chips left — {chips_txt}\n"
            f"Squad (id|name|pos|price|forecasts):\n{squad_lines}\n"
            f"Top players outside the squad (5-week forecast):\n{cand_lines}\n"
            f"Planner moves available this week (recomputed each later week for the squad you will have):\n"
            + "\n".join(proposals) + "\n"
            f"Outlook from this week's forecasts:\n" + "\n".join(outlook) + "\n\n"
            f"Output a strict JSON array of exactly {self.horizon} objects, one per gameweek in order: "
            "{\"transfer\": \"hold\"|\"best1\"|\"best2\", \"captain\": <player_id or null>, "
            "\"chip\": \"none\"|\"bench_boost\"|\"triple_captain\"|\"wildcard\"|\"free_hit\"}. "
            "A chip week ignores \"transfer\" for wildcard/free_hit. Respond with only the JSON array."
        )

    # ---------------------------------------------------------------- groups
    def evaluate_group(self, responses: Sequence[str]) -> List[RolloutResult]:
        baseline = self.baseline_total()
        results = []
        for response in responses:
            plan = parse_plan(response, self.horizon)
            if plan is None:
                results.append(RolloutResult(plan=None, realized=baseline, reward=UNPARSEABLE_REWARD))
                continue
            realized, detail = self.rollout(plan)
            results.append(RolloutResult(plan=plan, realized=realized, reward=realized - baseline, detail=detail))
        rewards = [r.reward for r in results]
        mean = sum(rewards) / len(rewards)
        std = math.sqrt(sum((x - mean) ** 2 for x in rewards) / len(rewards))
        for r in results:
            r.advantage = (r.reward - mean) / std if std > 1e-9 else 0.0
        return results


SEASON_LAST_WEEK = 38


def receding_value(env: "PlanEnvV2", first: WeekAction, chip_values: Optional[Dict[str, float]] = None) -> float:
    """Value of playing `first` in the window's first week, then the same-chips planner, re-planned
    from the state that action leaves, for the remaining weeks: the way the closed-loop evaluation
    executes one week at a time. Chips still held at the end of the window add `chip_values`
    (unless that half ends with the window), so spending a chip now has to beat keeping it.

    Scoring whole open-loop plans instead taught G5b two exploits that never pay in a season:
    scheduling chips "later" (re-planned weekly, they are never played) and dumping free hit and
    wildcard into the window's last week, where nothing after it is counted.
    """
    from dataclasses import replace

    first_week, carried = env.states[0], None
    r1, _, carried = PlanEnvV2([first_week], env.optimizer, chips=env.chips).rollout([first], return_state=True)
    total, chips_end = r1, carried["chips"]
    if len(env.states) > 1:
        nxt = replace(env.states[1], squad=carried["squad"], bank=carried["bank"], free_transfers=carried["free_transfers"])
        cont = PlanEnvV2([nxt] + list(env.states[2:]), env.optimizer, chips=carried["chips"])
        rest, _, end = cont.rollout(cont.baseline_plan(), return_state=True)
        total, chips_end = total + rest, end["chips"]
    last = env.states[-1].week
    if chip_values and last not in (FIRST_HALF_LAST_WEEK, SEASON_LAST_WEEK):
        total += sum(chip_values.get(chip, 0.0) for chip in chips_end[chip_half(last)])
    return total
